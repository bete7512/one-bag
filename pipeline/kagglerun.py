"""Run an exported GPU job on Kaggle from the command line: python -m pipeline kaggle run music

It needs the `kaggle` command line tool (pip install kaggle) and KAGGLE_API_TOKEN in .env. Then:

1. upload  The job folder that the stage exported (manifest.json, the job script, the keyframes)
           becomes a private Kaggle dataset, or a new version of it.
2. push    A small launcher is pushed as a private script on a GPU T4 x2 with internet on. It runs
           the job script that travels with the data, and only on the data of this job: a dataset
           that is still processing an upload would hand it the previous job.
3. wait    The run is polled until it ends, and its length is written to outputs/logs/kaggle_sessions.jsonl.
4. fetch   The output is downloaded and `ingest` puts the files into the cache and the measured
           GPU seconds of every clip into runs.jsonl. After an error the log is saved and shown.

The upload and the push are not model calls. The run log gets its lines from the ingest, one per
generated file, with the seconds and the peak memory the GPU job measured itself.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

from .core import Ctx, PipelineError, _append, now

SCRIPTS = {"music": "acestep_music.py", "shots": "wan22_i2v.py"}
RUNNING = {"QUEUED", "RUNNING", "NEW_SCRIPT"}
ENDED = {"COMPLETE", "ERROR", "CANCEL_REQUESTED", "CANCEL_ACKNOWLEDGED"}
LAUNCHER = '''"""Generated by `python -m pipeline kaggle run {stage}`. Runs the job script that travels with the job data."""
import json
import os
import runpy
from pathlib import Path

EXPECTED = {created!r}  # the job this run was pushed for
for manifest in sorted(Path("/kaggle/input").rglob("manifest.json")):
    job = json.loads(manifest.read_text(encoding="utf-8"))
    if job.get("stage") == {stage!r} and job.get("created") == EXPECTED:
        os.environ["JOB_DIR"] = str(manifest.parent)
        runpy.run_path(str(manifest.parent / {script!r}), run_name="__main__")
        break
else:
    raise SystemExit("The dataset attached to this run does not hold the job it was pushed for. "
                     "Kaggle may still be processing the upload: run the command again in a minute.")
'''


def kaggle(args: list[str], check: bool = True) -> subprocess.CompletedProcess:
    """Call the kaggle command line tool. The token comes from the environment and is never printed."""
    tool = shutil.which("kaggle") or str(Path(sys.executable).parent / "kaggle")
    if not Path(tool).exists():
        raise PipelineError("the kaggle command line tool is not installed. Run: pip install kaggle")
    if not (os.environ.get("KAGGLE_API_TOKEN") or os.environ.get("KAGGLE_KEY") or (Path.home() / ".kaggle").exists()):
        raise PipelineError("no Kaggle token. Create one at https://www.kaggle.com/settings/api and put KAGGLE_API_TOKEN=... into .env")
    done = subprocess.run([tool, *args], capture_output=True, text=True, encoding="utf-8", errors="replace")
    if check and done.returncode != 0:
        raise PipelineError(f"kaggle {' '.join(args[:2])} failed:\n{(done.stdout + done.stderr).strip()[-900:]}")
    return done


def owner() -> str:
    if os.environ.get("KAGGLE_USERNAME"):
        return os.environ["KAGGLE_USERNAME"]
    found = re.search(r"username:\s*(\S+)", kaggle(["config", "view"]).stdout)
    if not found or found.group(1) == "None":
        raise PipelineError("could not read the Kaggle username. Set KAGGLE_USERNAME in .env")
    return found.group(1)


def refs(stage: str) -> tuple[str, str]:
    """(dataset, kernel) names on Kaggle for one stage."""
    who = owner()
    return f"{who}/heritage-{stage}-job", f"{who}/heritage-{stage}"


def job_manifest(ctx: Ctx, stage: str) -> dict:
    path = ctx.out / stage / "kaggle_job" / "manifest.json"
    if not path.exists():
        raise PipelineError(f"no {stage} job is waiting. Run `python -m pipeline stage {stage}` first: it writes the job when something is missing.")
    return json.loads(path.read_text(encoding="utf-8"))


def dataset_state(dataset: str) -> dict | None:
    """Status and version of a dataset, or None when it does not exist yet."""
    done = kaggle(["datasets", "status", dataset, "--format", "json"], check=False)
    if done.returncode != 0:
        return None
    try:
        return json.loads(done.stdout)
    except json.JSONDecodeError:
        return {"status": done.stdout.strip()}


def upload(ctx: Ctx, stage: str, dataset: str) -> None:
    job_dir, staging = ctx.out / stage / "kaggle_job", ctx.out / stage / "kaggle_upload"
    manifest = job_manifest(ctx, stage)
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)
    for src in [job_dir / "manifest.json", job_dir / SCRIPTS[stage], *sorted((job_dir / "inputs").glob("*"))]:
        shutil.copy2(src, staging / src.name)  # flat: the upload ignores sub-folders
    meta = {"title": f"Heritage {stage} job", "id": dataset, "licenses": [{"name": "CC0-1.0"}]}
    (staging / "dataset-metadata.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")

    before = dataset_state(dataset)
    if before is None:
        kaggle(["datasets", "create", "-p", str(staging), "-q"])
    else:
        kaggle(["datasets", "version", "-p", str(staging), "-q", "-m", f"job {manifest['created']}"])
    ctx.say(f"  [{stage}] job uploaded to the private dataset {dataset} ({len(manifest['jobs'])} to generate). Waiting for Kaggle to process it.")
    for _ in range(60):
        state = dataset_state(dataset)
        newer = before is None or (state or {}).get("current_version_number") != before.get("current_version_number")
        if state and str(state.get("status", "")).lower() == "ready" and newer:
            return
        time.sleep(5)
    ctx.say(f"  [{stage}] the dataset is still processing after 5 minutes. Pushing anyway: the launcher refuses old data.")


def push(ctx: Ctx, stage: str, dataset: str, kernel: str) -> None:
    manifest = job_manifest(ctx, stage)
    folder = ctx.out / stage / "kaggle_kernel"
    if folder.exists():
        shutil.rmtree(folder)
    folder.mkdir(parents=True)
    (folder / "launch.py").write_text(LAUNCHER.format(stage=stage, created=manifest["created"], script=SCRIPTS[stage]), encoding="utf-8")
    meta = {"id": kernel, "title": f"Heritage {stage}", "code_file": "launch.py", "language": "python", "kernel_type": "script",
            "is_private": "true", "enable_gpu": "true", "enable_internet": "true", "machine_shape": "NvidiaTeslaT4",
            "dataset_sources": [dataset], "competition_sources": [], "kernel_sources": [], "model_sources": []}
    (folder / "kernel-metadata.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    for line in kaggle(["kernels", "push", "-p", str(folder)]).stdout.strip().splitlines() or ["pushed"]:
        ctx.say(f"  [{stage}] {line.strip()}")  # every line: a warning about the accelerator or the data would be printed here


def status(kernel: str) -> str:
    text = kaggle(["kernels", "status", kernel], check=False)
    found = re.search(r"(QUEUED|RUNNING|COMPLETE|ERROR|CANCEL_REQUESTED|CANCEL_ACKNOWLEDGED|NEW_SCRIPT)", (text.stdout + text.stderr).upper())
    return found.group(1) if found else "UNKNOWN"


def wait(ctx: Ctx, stage: str, kernel: str, poll_s: float = 30.0, limit_s: float = 6 * 3600) -> str:
    """Poll until the run ends. A status of the previous run can still show for a moment after a push, so an
    ending only counts once the new run has been seen queued or running, or two minutes have passed."""
    t0, seen_alive, last = time.time(), False, ""
    while True:
        state = status(kernel)
        if state != last:
            ctx.say(f"  [{stage}] {kernel}: {state.lower()} after {time.time() - t0:.0f}s")
            last = state
        seen_alive = seen_alive or state in RUNNING
        if state in ENDED and (seen_alive or time.time() - t0 > 120):
            break
        if time.time() - t0 > limit_s:
            raise PipelineError(f"{kernel} did not finish in {limit_s / 3600:.0f} hours. Look at it on kaggle.com, then: python -m pipeline kaggle fetch {stage}")
        time.sleep(poll_s)
    _append(ctx.out / "logs" / "kaggle_sessions.jsonl", {"ts": now(), "run_id": ctx.run_id, "stage": stage, "kernel": kernel,
                                                         "job_created": job_manifest(ctx, stage)["created"], "status": state,
                                                         "waited_s": round(time.time() - t0)})
    return state


def fetch(ctx: Ctx, stage: str, kernel: str) -> int:
    """Download the run's output and ingest it. Returns how many files entered the cache."""
    from . import music, shots

    expected = job_manifest(ctx, stage)["created"]
    folder = ctx.out / stage / "kaggle_output"
    if folder.exists():
        shutil.rmtree(folder)
    folder.mkdir(parents=True)
    kaggle(["kernels", "output", kernel, "-p", str(folder), "-o", "-q"], check=False)
    reports = sorted(folder.rglob("results.json"))
    if not reports:
        log = kaggle(["kernels", "logs", kernel], check=False)
        text = (log.stdout + log.stderr).strip()
        (folder / "kernel.log").write_text(text, encoding="utf-8")
        raise PipelineError(f"{kernel} produced no results. The end of its log (saved in {folder.relative_to(ctx.root)}/kernel.log):\n{text[-1800:]}")
    report = json.loads(reports[0].read_text(encoding="utf-8"))
    if report.get("job_created") not in (None, expected):
        raise PipelineError(f"the output on Kaggle belongs to an older job ({report.get('job_created')}), not this one ({expected}). Is the run still going?")
    return (shots if stage == "shots" else music).ingest(ctx, reports[0].parent)


def run(ctx: Ctx, action: str, stage: str, wait_for_it: bool = True) -> int:
    if ctx.mock:
        raise PipelineError("Kaggle jobs are real GPU work: run this without --mock")
    dataset, kernel = refs(stage)
    if action == "status":
        ctx.say(f"  [{stage}] {kernel}: {status(kernel).lower()}")
        return 0
    if action == "logs":
        log = kaggle(["kernels", "logs", kernel], check=False)
        ctx.say((log.stdout + log.stderr).strip()[-6000:])
        return 0
    if action == "run":
        upload(ctx, stage, dataset)
        push(ctx, stage, dataset, kernel)
        if not wait_for_it:
            ctx.say(f"  [{stage}] running on Kaggle. When it has ended: python -m pipeline kaggle fetch {stage}")
            return 0
        state = wait(ctx, stage, kernel)
        if state != "COMPLETE":
            ctx.say(f"  [{stage}] the run ended as {state.lower()}. Fetching what it left behind.")
    count = fetch(ctx, stage, kernel)
    ctx.say(f"  [{stage}] {count} file(s) ingested. Run `python -m pipeline film` to use them.")
    return 0
